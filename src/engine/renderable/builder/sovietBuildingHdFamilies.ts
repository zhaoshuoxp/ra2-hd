export type SovietBuildingHdFamily = keyof typeof sovietBuildingHdFamilies;
export const sovietBuildingHdNames = Object.keys(sovietBuildingHdFamilies) as SovietBuildingHdFamily[];
export function isSovietBuildingHdFamily(name: string): name is SovietBuildingHdFamily {
    return Object.hasOwn(sovietBuildingHdFamilies, name);
}
export function isSovietBuildingHdSource(source: Pick<HdSource, 'member' | 'sha256' | 'theater'>): boolean {
    return source.theater === 'TEMPERATE' && sovietBuildingHdNames.some(name =>
        sovietBuildingHdFamilies[name].members.some(m => m.member === source.member && m.sha256 === source.sha256));
}
export function matchesSovietBuildingHdSources(name: SovietBuildingHdFamily, sources: readonly HdSource[]): boolean {
    const family = sovietBuildingHdFamilies[name];
    const members = new Map(sources.map(source => [source.member, source]));
    return sources.length === family.members.length && members.size === sources.length && family.members.every(expected => {
        const source = members.get(expected.member);
        return source?.theater === family.theater && source.sha256 === expected.sha256
            && source.canvas.length === 2 && source.canvas.every((size, i) => size === family.canvas[i])
            && source.frames.length === expected.frames && source.frames.every((frame, i) => frame.nativeFrame === i);
    });
}
